#!/usr/bin/env python3
"""Copy each WordPress snippet into data/snippets.js so the hub can offer a Copy code button.
Strips the opening <?php line and the comment block, which Code Snippets doesn't want. Run before each release."""
import json, re, os
root = os.path.join(os.path.dirname(__file__), "..")
out = {}
for key, name in [("seo", "wordpress-snippet.php"), ("checker", "wordpress-page-checker.php"), ("ga4", "wordpress-ga4.php")]:
    src = open(os.path.join(root, "docs", name)).read()
    src = re.sub(r"^<\?php\s*", "", src)
    src = re.sub(r"^/\*\*.*?\*/\s*", "", src, count=1, flags=re.S)
    out[key] = src.strip() + "\n"
with open(os.path.join(root, "data", "snippets.js"), "w") as f:
    f.write("/* Generated by scripts/build-snippets.py from docs/*.php. Don't edit by hand. */\nwindow.WPT_SNIPPETS = " + json.dumps(out, indent=1) + ";\n")
print("snippets:", {k: len(v) for k, v in out.items()})
